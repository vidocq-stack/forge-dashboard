-- forge-dashboard schema, version 1. Every timestamp is a timestamptz; the application writes UTC instants.

-- The organisations shown as tabs, in display order.
CREATE TABLE tracked_org (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT        NOT NULL UNIQUE,
    position   INTEGER     NOT NULL,
    active     BOOLEAN     NOT NULL,
    added_by   TEXT,
    added_at   TIMESTAMPTZ
);

-- The repositories of the tracked organisations; the id is CodeFloe's.
CREATE TABLE repo (
    id                 BIGINT      PRIMARY KEY,
    org                TEXT        NOT NULL,
    name               TEXT        NOT NULL,
    default_branch     TEXT        NOT NULL,
    archived           BOOLEAN     NOT NULL,
    empty_repo         BOOLEAN     NOT NULL,
    -- 'none' disables Sonar for the repository; null applies the naming rule of SonarKeys.
    sonar_key_override TEXT,
    -- Cursor of the commits loop: the committer date of the newest commit read.
    last_commit_at     TIMESTAMPTZ
);
CREATE INDEX repo_org ON repo (org, name);

-- The Actions runners; the id is CodeFloe's.
CREATE TABLE runner (
    id                BIGINT      PRIMARY KEY,
    org               TEXT        NOT NULL,
    uuid              TEXT        NOT NULL UNIQUE,
    name              TEXT        NOT NULL,
    labels            TEXT,
    version           TEXT,
    last_status       TEXT        NOT NULL,
    -- Slots of the runner; null uses the capacity observed over 7 days.
    capacity_override INTEGER,
    last_seen_at      TIMESTAMPTZ
);
CREATE INDEX runner_org ON runner (org);

CREATE TABLE runner_status_change (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_id  BIGINT      NOT NULL,
    org        TEXT        NOT NULL,
    status     TEXT        NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX runner_status_change_org_at ON runner_status_change (org, changed_at);

-- One execution of a job by a runner, keyed by the Actions task id. stopped_at is null while it runs.
CREATE TABLE job_execution (
    task_id    BIGINT      PRIMARY KEY,
    job_id     BIGINT      NOT NULL,
    run_id     BIGINT      NOT NULL,
    org        TEXT        NOT NULL,
    repo       TEXT        NOT NULL,
    -- Null until the head of the log names the runner.
    runner_id  BIGINT,
    pr_number  INTEGER,
    job_name   TEXT,
    run_title  TEXT,
    event      TEXT,
    ref        TEXT,
    commit_sha TEXT,
    status     TEXT        NOT NULL,
    html_url   TEXT,
    started_at TIMESTAMPTZ NOT NULL,
    stopped_at TIMESTAMPTZ
);
CREATE INDEX job_execution_org_stopped ON job_execution (org, stopped_at);
CREATE INDEX job_execution_runner_started ON job_execution (runner_id, started_at);
CREATE INDEX job_execution_pr ON job_execution (org, repo, pr_number);

-- The waiting queue, aggregated per minute: the maximum seen during the minute.
CREATE TABLE queue_sample (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org     TEXT        NOT NULL,
    minute  TIMESTAMPTZ NOT NULL,
    waiting INTEGER     NOT NULL,
    running INTEGER     NOT NULL
);
CREATE UNIQUE INDEX queue_sample_org_minute ON queue_sample (org, minute);

-- The last known state of the open pull requests, read back at start-up. The id is 'org/repo#n'.
CREATE TABLE pull_request_state (
    id           TEXT        PRIMARY KEY,
    org          TEXT        NOT NULL,
    repo         TEXT        NOT NULL,
    number       INTEGER     NOT NULL,
    title        TEXT,
    author_login TEXT,
    head_ref     TEXT,
    head_sha     TEXT,
    html_url     TEXT,
    draft        BOOLEAN     NOT NULL,
    ci_state     TEXT        NOT NULL,
    created_at   TIMESTAMPTZ,
    updated_at   TIMESTAMPTZ,
    observed_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX pull_request_state_org ON pull_request_state (org, repo);

-- The last Sonar measures of a project ('key') or of a pull request ('key#n').
CREATE TABLE sonar_snapshot (
    id                       TEXT             PRIMARY KEY,
    sonar_key                TEXT             NOT NULL,
    pr_number                INTEGER,
    org                      TEXT,
    repo                     TEXT,
    ncloc                    BIGINT,
    tests                    BIGINT,
    coverage                 DOUBLE PRECISION,
    test_failures            BIGINT,
    test_errors              BIGINT,
    bugs                     BIGINT,
    vulnerabilities          BIGINT,
    code_smells              BIGINT,
    duplicated_lines_density DOUBLE PRECISION,
    gate                     TEXT             NOT NULL,
    measured_at              TIMESTAMPTZ      NOT NULL
);

-- One commit of a default branch, classified. The id is 'org/repo@sha'. Kept without limit.
CREATE TABLE commit_stat (
    id             TEXT        PRIMARY KEY,
    sha            TEXT        NOT NULL,
    org            TEXT        NOT NULL,
    repo           TEXT        NOT NULL,
    authored_at    TIMESTAMPTZ NOT NULL,
    author_name    TEXT,
    author_email   TEXT,
    author_login   TEXT,
    message        TEXT,
    additions      INTEGER,
    deletions      INTEGER,
    kind           TEXT        NOT NULL,
    -- The resolved human; null for a bot commit.
    human_key      TEXT,
    -- The agent families of the Co-Authored-By trailers, comma-separated, sorted; null without agent.
    agent_families TEXT,
    claude_session TEXT,
    raw_trailers   TEXT
);
CREATE INDEX commit_stat_authored ON commit_stat (authored_at);
CREATE INDEX commit_stat_org_authored ON commit_stat (org, authored_at);

-- One pull request, for the opened and merged counts per login. The id is 'org/repo#n'.
CREATE TABLE pr_stat (
    id           TEXT        PRIMARY KEY,
    org          TEXT        NOT NULL,
    repo         TEXT        NOT NULL,
    number       INTEGER     NOT NULL,
    author_login TEXT        NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    merged_at    TIMESTAMPTZ
);
CREATE INDEX pr_stat_created ON pr_stat (created_at);
CREATE INDEX pr_stat_merged ON pr_stat (merged_at);

-- The preferences of a signed-in user.
CREATE TABLE user_pref (
    login       TEXT    PRIMARY KEY,
    view_mode   TEXT    NOT NULL,
    period_days INTEGER NOT NULL,
    last_org    TEXT
);

-- The freshness of each collector loop, shown in the footer.
CREATE TABLE collector_state (
    loop_name       TEXT PRIMARY KEY,
    last_success_at TIMESTAMPTZ,
    last_error_at   TIMESTAMPTZ,
    last_error      TEXT
);
